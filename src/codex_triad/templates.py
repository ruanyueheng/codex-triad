"""Official-format project-scoped Codex agents and orchestration policy."""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Settings:
    main_model: str = "gpt-6.1-sol"
    advisor_model: str = "gpt-6-astra"
    worker_model: str = "gpt-6-luna"
    main_effort: str = "high"
    advisor_effort: str = "high"
    worker_effort: str = "medium"
    max_subagents: int = 3


AGENT_NAMES = ("triad_architect", "triad_explorer", "triad_researcher", "triad_triage")
EFFORTS = ("none", "minimal", "low", "medium", "high", "xhigh", "max", "ultra")
MANAGED_LINE = "# codex-triad:managed"
BEGIN = "<!-- CODEX-TRIAD:BEGIN -->"
