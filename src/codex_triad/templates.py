def agent_toml(name: str, settings: Settings) -> str:
    # Minimal TOML escaping is safe because we serialize all externally configurable values
    # with JSON strings (double-quoted JSON strings are valid TOML basic strings for these IDs).
    import json

    description, instructions = AGENT_DEFINITIONS[name]
    instructions = ("Input contract: one goal, bounded scope/paths, relevant evidence, constraints and expected output.\n"
                    "If required evidence is missing, name it explicitly; do not invent facts.\n" + instructions)
    model = settings.advisor_model if name == "triad_architect" else settings.worker_model
    effort = settings.advisor_effort if name == "triad_architect" else settings.worker_effort
    # multiline literal string, avoid accidental closing delimiter in future instructions
    assert "'''" not in instructions
    return (
        "# Generated by codex-triad; see .codex/triad-state.json for ownership.\n"
        f"name = {json.dumps(name)}\n"
        f"description = {json.dumps(description, ensure_ascii=False)}\n"
        f"model = {json.dumps(model)}\n"
        f"model_reasoning_effort = {json.dumps(effort)}\n"
        f"developer_instructions = '''\n{instructions}\n'''\n"
    )


def instructions_block(settings: Settings) -> str:
    return f"""{BEGIN}
## Codex Triad orchestration (project-local)

**Execution model:** `triad_explorer`, `triad_researcher`, and `triad_triage` use `{settings.worker_model}`.
`triad_architect` uses `{settings.advisor_model}`. The main session targets `{settings.main_model}`.
These are *configured intentions*, not proof of actual model selection.

**Main session responsibility:** clarify acceptance criteria; own plans, source edits, focused tests,
final integration and user communications. Keep decisions and evidence in the main thread.
Spawn only independent, narrow research tasks; wait for reports, not full raw transcripts.
Prefer zero subagents for trivial work. Never invent a completed delegation or a model identity.

**Delegation contract:** give each worker a goal, exact scope, relevant paths and expected output.
Ask workers to return evidence paths, assumptions and a short summary (not full files/logs).
Avoid concurrent writes. The coordinator alone edits unless the user specifically wants otherwise.

**Advisor checkpoints (instruction-based, not an enforced hook):**
1. Before a consequential/irreversible architecture, API, security or data-migration decision.
2. After **two attempts with the same failure signature** without a meaningful change in diagnosis.
3. Before committing a **nontrivial** change, review the actual diff, risks and observed tests.
Skip the advisor for low-risk chores and do not repeatedly call it on unchanged evidence.
The architect returns APPROVE / APPROVE_WITH_CONDITIONS / BLOCK / INSUFFICIENT_EVIDENCE;
the main session owns the decision and must not conceal blockers.

**Evidence and permissions:** never claim a test passed without a recorded result. Do not
commit, push, deploy, remove user data or relax sandbox settings without user authorization.
The custom agent files do NOT create security boundaries: all agents inherit the parent
session's provider, MCP tools and permission/sandbox configuration. For genuinely read-only
reviews, start an appropriately restricted parent turn.

**Failure modes:** if spawning fails or a configured model is unavailable, report the exact
error and fall back transparently to a single-agent workflow only with an explicit note.
Never silently assert the three-model architecture was used. Track outcome, test results,
active agents and model verification as separate facts.
{END}"""


def required_config(settings: Settings) -> tuple[dict[str, str | int | bool], dict[str, str | int | bool]]:
    root: dict[str, str | int | bool] = {
        "model": settings.main_model,
        "model_reasoning_effort": settings.main_effort,
    }
    agents: dict[str, str | int | bool] = {
        "enabled": True,
        "max_concurrent_threads_per_session": settings.max_subagents,
        "default_subagent_model": settings.worker_model,
        "default_subagent_reasoning_effort": settings.worker_effort,
    }
    return root, agents
